CREATE TABLE IF NOT EXISTS xendit_payments (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  trainee_fee_id INT UNSIGNED NOT NULL,
  user_id INT UNSIGNED NOT NULL,
  flow ENUM('invoice', 'payment-link') NOT NULL,
  reference_id VARCHAR(100) NOT NULL,
  provider_id VARCHAR(150) DEFAULT NULL,
  amount DECIMAL(12,2) NOT NULL,
  status ENUM('pending', 'paid', 'failed') NOT NULL DEFAULT 'pending',
  checkout_url VARCHAR(1000) NOT NULL,
  raw_response JSON DEFAULT NULL,
  paid_at DATETIME DEFAULT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_xendit_reference (reference_id),
  KEY idx_xendit_fee_status (trainee_fee_id, status),
  CONSTRAINT fk_xendit_payment_fee FOREIGN KEY (trainee_fee_id) REFERENCES trainee_fees (trainee_fee_id) ON DELETE CASCADE,
  CONSTRAINT fk_xendit_payment_user FOREIGN KEY (user_id) REFERENCES users (user_id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
